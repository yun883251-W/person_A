# 预览对象是当前磁盘原文；可接收引用的 content_hash 用于核对是否已发生变化。
# 当前哈希与引用不同，或文件已删除时明确提示无法按旧引用核对，不能冒充历史原文。
# 原文预览不触发文档入库、向量检索、模型调用或索引刷新。

