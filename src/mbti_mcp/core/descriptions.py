def get_type_description(mbti_type):
    """根据 MBTI 类型代码获取详细描述

    参数:
        mbti_type: 4 字母类型代码, 如 'INTJ', 'ENFP'（大小写不敏感）

    返回:
        dict: 包含名称、概述、特质、优势、成长空间、职业和关系模式的完整描述
              类型代码无效时返回 None

    用法:
        desc = get_type_description('INTJ')
        print(desc['name'])     # 'INTJ — 建筑师'
        print(desc['traits'])   # [...]
    """
    # 统一转大写处理, 确保大小写不敏感的查询
    mbti_type = mbti_type.upper().strip()
    return MBTI_DESCRIPTIONS.get(mbti_type)


def get_type_name(mbti_type):
    """根据类型代码获取中文名称

    参数:
        mbti_type: 4 字母类型代码

    返回:
        str: 中文名称, 如 '建筑师'; 无效类型返回原始代码
    """
    mbti_type = mbti_type.upper().strip()
    info = MBTI_TYPE_NAMES.get(mbti_type)
    return info[0] if info else mbti_type


